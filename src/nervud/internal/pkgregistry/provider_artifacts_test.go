package pkgregistry

import (
	"testing"

	ipcv1 "github.com/nervus-os/nervus-ipc/protocol/ipcv1"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// TestMessageHasUnknown_ScalarValuedMapDoesNotPanic pins that map<string,string> doesn't panic.
//
// # This bug stopped nervud starting
//
// In protoreflect, a map field's FieldDescriptor.Kind() is always MessageKind
// (a map on the wire is a repeated synthetic entry message), regardless of its value type.
// So judging by Kind() would send map<string,string> into the "this is a sub-message" branch,
// which calls value.Message() on a string value, and protoreflect panics straight away.
//
// ProviderDescriptor.resources[].labels is exactly map<string,string>
// (provider_descriptor.proto:196). So any system package declaring a resource with labels
// made the boot scan panic: scanSystemImage -> loadProviderArtifacts ->
// messageHasUnknown, showing up as nervud exiting with status=2 and the whole system failing to start.
func TestMessageHasUnknown_ScalarValuedMapDoesNotPanic(t *testing.T) {
	descriptor := &ipcv1.ProviderDescriptor{
		Resources: []*ipcv1.ManagedResource{{
			StableRole: "cam.front",
			// The key point: the value is a string, not a message
			Labels: map[string]string{"nervus.camera.facing": "front"},
		}},
	}
	// No recover: a panic should fail this test and show the stack, which is exactly what was seen in production
	if messageHasUnknown(descriptor.ProtoReflect(), 0) {
		t.Error("a message whose fields are all known was judged to contain unknown fields")
	}
}

// TestMessageHasUnknown_StillDetectsUnknownInNestedMessage: the fix mustn't break the detection itself.
// Its purpose is refusing provider artefacts with unknown fields (which means they were generated by a newer
// schema that this kernel partly doesn't know, and silently ignoring them would let the contract drift quietly).
func TestMessageHasUnknown_StillDetectsUnknownInNestedMessage(t *testing.T) {
	descriptor := &ipcv1.ProviderDescriptor{
		Resources: []*ipcv1.ManagedResource{{StableRole: "cam.front"}},
	}
	// Put an unknown field (field 50000, varint) into a nested message
	descriptor.Resources[0].ProtoReflect().SetUnknown(
		protoreflect.RawFields([]byte{0x80, 0x86, 0x18, 0x01}))

	if !messageHasUnknown(descriptor.ProtoReflect(), 0) {
		t.Error("an unknown field in a nested message wasn't found; this gate does nothing")
	}
}

// TestMessageHasUnknown_DetectsUnknownInRepeatedMessage: unknown fields in repeated messages
// must still be found.
//
// Together with the scalar map case, this shows the fix "dispatches by value type" rather than "skips all composite fields".
//
// There's no case for "message-valued maps" because no such field exists in the whole proto set: the existing maps
// are all map<string,string> (the labels in provider_descriptor / envelope / resourcedir), and InterfaceSchemaBundleSet.bundles is repeated, not a map.
// Making a .proto type that exists only in tests for this would buy coverage that matches no real data;
// the MessageKind branch in the fix already judges by value type.
func TestMessageHasUnknown_DetectsUnknownInRepeatedMessage(t *testing.T) {
	bundles := &ipcv1.InterfaceSchemaBundleSet{
		Bundles: []*ipcv1.InterfaceSchemaBundle{{InterfaceId: "nervus.interface.demo"}},
	}
	bundles.Bundles[0].ProtoReflect().SetUnknown(
		protoreflect.RawFields([]byte{0x80, 0x86, 0x18, 0x01}))

	if !messageHasUnknown(bundles.ProtoReflect(), 0) {
		t.Error("an unknown field in a repeated message wasn't found")
	}
}
