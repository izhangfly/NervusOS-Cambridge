// This file implements built-in endpoints: implemented by nervud itself, not Interfaces of external Services.
//
// # Why they're needed
//
// Some capabilities naturally live in the kernel and can't be provided by a Provider: Safety re-arm (releasing the stop latch),
// the machine's health level, the controlling-party snapshot. They either act directly on kernel state or are kernel state.
//
// But Apps and system services need them, and the only call shape on the control plane is
// ResolveEndpoint -> Request -> Response. So there are two options: add a new body to the Envelope,
// or let nervud own endpoints itself.
//
// envelope.proto rules out the first: "before adding a new body, ask whether it's one of the eight things
// above; if not, it should be a method on some Interface." Re-arm isn't any of establishing a connection,
// discovering an endpoint, making a call, returning a result, cancelling, subscribing, pushing events or keeping the connection alive.
//
// So it takes the second: nervud registers built-in endpoints, and callers use completely standard Resolve+Request
// without knowing or needing to know whether the other side is the kernel or a Provider.
//
// # Three differences from external registration
//
//  1. It doesn't go through the RegisterEndpoint wire, so it needs no manifest exports declaration and doesn't check
//     perm.service.register: the kernel isn't a Package, and those two checks mean nothing for it.
//  2. There's no conn. An external registration's conn is used for Dispatch forwarding and invalidation on disconnect;
//     built-in execution happens in-process with no connection to drop, so it's always live.
//  3. Route returns a Handler rather than a TargetConn, and ipc takes the local execution branch on that basis.
//
// # Permissions are still decided as usual
//
// Built-in doesn't mean exempt. Resolve and Route use the central catalog's interface-level and method-level
// permissions. "Who implements it" and "who can call it" are two independent things.
package endpoint

import (
	"context"
	"fmt"

	ipcv1 "github.com/nervus-os/nervus-ipc/protocol/ipcv1"

	"github.com/nervus-os/nervud/internal/catalog"
	"github.com/nervus-os/nervud/internal/identity"
	"github.com/nervus-os/nervud/internal/pkgregistry"
)

// BuiltinCall carries the same trusted call context that an external dispatch
// route has. Conn is deliberately included for route-bound transfer control.
type BuiltinCall struct {
	Context  context.Context
	Conn     ConnHandle
	Caller   identity.Caller
	MethodID uint32
	Payload  []byte
}

type BuiltinResult struct {
	// Payload is the response payload on success; its type is decided by MethodMeta.response_type.
	Payload []byte

	// ErrorDetail is the typed detailed cause on failure; its type is decided by MethodMeta.error_detail_type.
	// Empty means there's only a Code, with no finer reason.
	//
	// # Why not reuse Payload
	//
	// If it were reused, "should these bytes be decoded as response_type or error_detail_type" would depend on
	// the Code, a convention you'd only know by reading the implementation. With two fields, filling in the wrong one is
	// a type mismatch, exposed at compile time or validation time.
	//
	// # Why built-ins can carry a detail and external Providers can't
	//
	// A Provider's error_detail is currently rejected outright by the kernel (see method_gate.go):
	// there's no machine-readable authorisation between StatusCode and domain reason, so a detail from an external
	// process looks "authenticated" but has no semantic basis.
	//
	// Built-ins are different: the detail is generated by kernel code, from the same decision as the Code. This isn't a back door
	// for built-ins; that concern simply doesn't apply here.
	ErrorDetail []byte

	Code ipcv1.StatusCode
}

// BuiltinHandler executes one in-kernel endpoint method. The handler returns a
// wire status explicitly; unclassified Go errors must not leak into protocol
// behavior.
type BuiltinHandler func(BuiltinCall) BuiltinResult

// BuiltinSubscribeCall is one subscription admission query.
//
// It only happens when the event declares EventMeta.scoped. Undeclared events are endpoint-scoped:
// whoever can Resolve the endpoint can subscribe, with no further question.
type BuiltinSubscribeCall struct {
	Caller  identity.Caller
	EventID uint32
	// Scope is the raw Subscribe.scope, i.e. the instance the caller wants to observe.
	//
	// The kernel already understands it: scope is a uint64 on the Envelope and needs no decoding
	// by the Provider's schema. The implementation only has to answer "may this caller see it".
	Scope uint64
}

// BuiltinSubscribeResult is the admission result. Code OK means admitted; other values go back to the subscriber unchanged.
type BuiltinSubscribeResult struct {
	Code ipcv1.StatusCode
}

// BuiltinSubscribeAdmitter decides whether a subscription is admitted.
//
// # Why this decision must happen at Subscribe, not as a filter at fan-out
//
// Subscribing and then dropping events one by one would make the caller think it's observing, and wait forever for an event that never comes.
// "Can't subscribe" is a clear failure, and the caller knows at once what to do.
//
// # Built-ins and external Providers are decided differently, over the same wire
//
// Built-in ownership belongs to the kernel itself (operations are nervud's), so one lookup can answer it,
// hence this callback. Only an external Provider knows its own ownership, which it registers in advance with BindEventScope(54)
// into internal/ipc's ownership table. Both paths use the same body on Subscribe and
// the same scope field; clients can't tell the difference and don't need to.
//
// This function runs in the connection's read loop, so implementations must not block or panic.
// It's kernel code, and its authors guarantee both.
type BuiltinSubscribeAdmitter func(BuiltinSubscribeCall) BuiltinSubscribeResult

// RegisterBuiltin registers an Interface implemented by nervud itself.
//
// Called at wiring (main.go), never added or removed dynamically at run time: built-in capabilities are part of the kernel,
// fixed with the binary. Registering the same interfaceID twice returns an error rather than overwriting: a silent overwrite
// would make "which implementation is in effect" depend on wiring order, the hardest kind of problem to track down.
func (m *Module) RegisterBuiltin(interfaceID string, major, minor uint32, h BuiltinHandler) error {
	if m == nil {
		return fmt.Errorf("endpoint: nil module")
	}
	if interfaceID == "" || h == nil {
		return fmt.Errorf("endpoint: builtin %q requires a non-empty id and handler", interfaceID)
	}
	snapshot := m.snapshot()
	if snapshot == nil {
		return fmt.Errorf("endpoint: builtin %q has no authoritative catalog snapshot", interfaceID)
	}
	provider, ok := snapshot.ProviderInterface(
		catalog.KernelPackageID, interfaceID, major)
	if !ok || provider.PackageID != catalog.KernelPackageID ||
		provider.ComponentID == "" ||
		provider.Definition.InterfaceID != interfaceID ||
		provider.Definition.Major != major ||
		provider.ProviderOwner.Kind != catalog.SourceKindKernel {
		return fmt.Errorf("endpoint: builtin %q@%d is not owned by the kernel catalog",
			interfaceID, major)
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	for _, reg := range m.byInterface[interfaceID] {
		if reg.builtin != nil && reg.ifaceMajor == major {
			return fmt.Errorf("endpoint: builtin %q@%d already registered", interfaceID, major)
		}
	}

	m.builtinSeq++
	reg := &serviceRegistration{
		id:                   m.builtinSeq,
		packageID:            catalog.KernelPackageID,
		componentID:          provider.ComponentID,
		interfaceID:          interfaceID,
		ifaceMajor:           major,
		ifaceMinor:           minor,
		schemaHash:           append([]byte(nil), provider.Definition.SchemaHash...),
		definitionGeneration: provider.Definition.DefinitionGeneration,
		providerGeneration:   provider.DefinitionGeneration,
		// Built-in endpoints are visible across Packages: they're platform capabilities, not part of any one package.
		// Whether they can be called is decided by permissions, not visibility.
		visibility: visibilityPublicForBuiltin,
		generation: 1,
		// Always live: there's no connection to drop. External registrations go false when their conn drops;
		// built-in execution happens in-process and is available as long as nervud is alive.
		live:    true,
		builtin: h,
	}
	m.byInterface[interfaceID] = append(m.byInterface[interfaceID], reg)
	return nil
}

// BuiltinEndpointID returns the registration handle of a built-in interface.
//
// Event fan-out needs it: the fan-out key is (ProviderConn, EndpointID, EventID, Scope), and a built-in
// has no conn, so the EndpointID is the only thing that can locate the event source.
//
// It must be the same number RouteEvent gives subscribers. Subscription registration uses RouteEvent's
// ProviderEndpointID and fan-out uses this return value; if they differ the subscriber never gets events,
// and neither side reports an error, because each looks like a legal key on its own.
func (m *Module) BuiltinEndpointID(interfaceID string, major uint32) (uint64, bool) {
	if m == nil {
		return 0, false
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	for _, reg := range m.byInterface[interfaceID] {
		if reg.builtin != nil && reg.ifaceMajor == major {
			return reg.id, true
		}
	}
	return 0, false
}

// RegisterBuiltinSubscriber attaches subscription admission to an already registered built-in interface.
//
// It must be called after RegisterBuiltin. It's two steps rather than an extra parameter on RegisterBuiltin:
// only one of the four built-ins needs admission, and making the other three write nil would make "not needed" and
// "forgot to write it" look exactly the same in the code.
func (m *Module) RegisterBuiltinSubscriber(
	interfaceID string, major uint32, admit BuiltinSubscribeAdmitter,
) error {
	if m == nil {
		return fmt.Errorf("endpoint: nil module")
	}
	if admit == nil {
		return fmt.Errorf("endpoint: builtin %q@%d requires a non-nil admitter",
			interfaceID, major)
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	for _, reg := range m.byInterface[interfaceID] {
		if reg.builtin == nil || reg.ifaceMajor != major {
			continue
		}
		if reg.subscribeAdmit != nil {
			// Registering twice would make "which admission is in effect" depend on wiring order. The same reason RegisterBuiltin
			// refuses duplicate registrations.
			return fmt.Errorf("endpoint: builtin %q@%d already has a subscribe admitter",
				interfaceID, major)
		}
		reg.subscribeAdmit = admit
		return nil
	}
	return fmt.Errorf("endpoint: builtin %q@%d is not registered", interfaceID, major)
}

// visibilityPublicForBuiltin is the visibility of built-in endpoints.
//
// A named constant rather than writing pkgregistry.VisibilityPublic directly, so there's a place to explain
// "why built-ins are public": built-in capabilities belong to the platform, not to any one
// Package, so the semantics of "visible only within the same package" don't exist. Whether they can be called is decided by permissions.
const visibilityPublicForBuiltin = pkgregistry.VisibilityPublic
