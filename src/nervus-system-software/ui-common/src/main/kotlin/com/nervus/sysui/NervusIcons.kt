fun iconForPackage(packageId: String): ImageVector = when (packageId) {
    "nervus.settings" -> NervusIcons.Settings
    "nervus.filemanager" -> NervusIcons.Folder
    "nervus.store" -> NervusIcons.Store
    "com.nervus.robotarm" -> NervusIcons.RobotArm
    else -> NervusIcons.Apps
}

private fun symbol(
    name: String,
    pathData: String,
    autoMirror: Boolean = false,
): ImageVector = ImageVector.Builder(
    name = name,
    defaultWidth = 24.dp,
    defaultHeight = 24.dp,
    viewportWidth = 960f,
    viewportHeight = 960f,
    autoMirror = autoMirror,
).addGroup(
    translationY = 960f,
).addPath(
    pathData = PathParser().parsePathString(pathData).toNodes(),
    fill = SolidColor(Color.Black),
).clearGroup().build()
